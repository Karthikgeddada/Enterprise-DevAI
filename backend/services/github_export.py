"""Export a finished DevTeam AI run to GitHub as a real repository.

Uses PyGithub with the user's personal access token (classic token with
"repo" scope, or a fine-grained token with "Contents: write"). The token is
used for this one request and never stored, logged, or persisted.

Files are pushed as individual commits (repo.create_file) — one API call
per file. Generated projects are small (5-20 files), so this stays well
within GitHub's rate limits and keeps the export dependency-free on git
binaries (Render's slim images don't ship git).
"""
import re
from typing import Any, Dict, List


def sanitize_repo_name(name: str) -> str:
    """Turn any prompt-derived string into a valid GitHub repo name."""
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "-", (name or "").strip().lower())
    cleaned = re.sub(r"\.{2,}", ".", cleaned)
    cleaned = re.sub(r"^[._-]+|[._-]+$", "", cleaned)
    cleaned = cleaned[:90]
    return cleaned or "devteam-project"


def push_project_to_github(
    files: List[Dict[str, str]],
    repo_name: str,
    token: str,
    description: str = "",
) -> Dict[str, Any]:
    """Create a public repo and push every file. Returns repo info.

    Raises github.GithubException subclasses on any failure; the caller
    (routes/api.py) maps them to clean HTTP errors.
    """
    from github import Github, GithubException

    g = Github(token)
    user = g.get_user()
    login = user.login

    base = sanitize_repo_name(repo_name)
    name = base
    repo = None
    for attempt in range(5):
        try:
            repo = user.create_repo(
                name,
                description=description or "Project generated by DevTeam AI",
                private=False,
                auto_init=False,
            )
            break
        except GithubException as e:
            # 422 = name already exists under this account: retry with a suffix.
            if e.status == 422 and attempt < 4:
                name = f"{base}-{attempt + 2}"
                continue
            raise

    for f in files:
        repo.create_file(
            f["path"],
            f"feat: add {f['path']}",
            f["content"],
            branch="main",
        )

    return {"repo_name": f"{login}/{name}", "repo_url": repo.html_url}


def open_pull_request(
    files: List[Dict[str, str]],
    repo_full_name: str,
    token: str,
    pr_title: str = "",
    pr_body: str = "",
) -> Dict[str, Any]:
    """Open a pull request with the run's files on an EXISTING repo.

    Creates branch devteam-ai/<timestamp> from the repo's default branch,
    commits each file onto it, then opens the PR. repo_full_name is
    "owner/name". Raises ValueError for user-fixable problems (missing or
    empty repo) — the route maps those to HTTP 400; GithubException
    propagates for auth/permission failures (mapped to 401/502).
    """
    from datetime import datetime, timezone

    from github import Github, GithubException

    g = Github(token)
    try:
        repo = g.get_repo(repo_full_name)
    except GithubException as e:
        if e.status == 404:
            raise ValueError(f"Repo '{repo_full_name}' not found (check the owner/name and the token's access).")
        raise

    base_branch = repo.default_branch or "main"
    branch = f"devteam-ai/{datetime.now(timezone.utc):%Y%m%d-%H%M%S}"

    # Branch from the head of the default branch. An empty repo (no commits
    # yet) has no refs — a PR is meaningless there, so fail with guidance.
    try:
        base_sha = repo.get_git_ref(f"heads/{base_branch}").object.sha
    except GithubException as e:
        if e.status == 404:
            raise ValueError(
                f"'{repo_full_name}' has no commits yet — push it as a new repo instead of a PR."
            )
        raise
    repo.create_git_ref(ref=f"refs/heads/{branch}", sha=base_sha)

    for f in files:
        repo.create_file(
            f["path"],
            f"feat: add {f['path']}",
            f["content"],
            branch=branch,
        )

    pr = repo.create_pull(
        title=pr_title or "DevTeam AI: generated project",
        body=pr_body or "Project generated by DevTeam AI.",
        head=branch,
        base=base_branch,
    )
    return {
        "pr_url": pr.html_url,
        "pr_number": pr.number,
        "branch": branch,
        "repo_name": repo_full_name,
    }
